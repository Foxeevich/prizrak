// lichina.js — привратник узла: турист или туннель?
//
// Каждый входящий HTTP-запрос сначала проходит здесь. Задача — отличить
// клиента туннеля от постороннего (браузер, поисковый бот, зонд цензора) БЕЗ
// единого различимого снаружи признака:
//
//   • турист/зонд  → отдаём НАСТОЯЩИЙ сайт (site.js), как отдал бы любой сервер;
//   • клиент туннеля → поднимаем «Тень» и качаем трафик.
//
// Как отличаем без магического байта: клиент кладёт первое сообщение «Тени» в
// тело POST на обычный endpoint сайта (форма обратной связи). Узел ПРОБУЕТ
// разобрать его своим приватным ключом. Сойдётся AEAD-доказательство — это наш;
// не сойдётся — это не наш, и мы просто отвечаем как форма. Зонд, приславший
// мусор в ту же форму, получает ровно то же «Спасибо!», что и настоящий
// посетитель. Разного поведения нет — значит и различить нельзя.
//
// Тонкость с таймингом: чтобы не выдать себя разницей во времени ответа
// (криптопроверка занимает микросекунды, но всё же), проверку делаем ВСЕГДА,
// даже когда тело заведомо не наше по длине — и на успех, и на провал тратим
// одинаковый путь.

import { nodeHandshake } from './shadow.js';
import { makeSite } from './site.js';
import { makeFrameReader } from './carrier.js';

/**
 * Создать привратника.
 * @param {object} p
 * @param {string} p.nodePriv — приватный X25519-ключ узла (hex).
 * @param {Map}    p.seen — общее хранилище использованных nonce (антиповтор).
 * @param {object} p.site — сайт-личина; по умолчанию makeSite().
 * @param {function} p.now — источник времени в секундах (для тестов).
 */
export function makeDoorman({ nodePriv, seen = new Map(), site = makeSite(), now } = {}) {
  if (!nodePriv) throw new Error('нужен приватный ключ узла');
  const nowSec = () => (now ? now() : Math.floor(Date.now() / 1000));

  /**
   * Обработать HTTP-запрос.
   * @returns один из:
   *   { kind: 'site', response }                — отдать сайт (турист/зонд);
   *   { kind: 'tunnel', session, reply, reader } — это наш клиент.
   *     reply — байты ответа узла (эфемер), их кладём в ТЕЛО ответа-несущей;
   *     reader — сборщик последующих кадров данных из тела запроса.
   */
  function handle({ method, path, body }) {
    const asSite = () => ({ kind: 'site', response: site.handle(method, path, body) });

    // Дверь живёт только за ingest-endpoint'ом и только для POST с телом.
    // Всё прочее — заведомо сайт, но ключ мы всё равно НЕ трогаем: обычные
    // страницы криптопроверки не касаются, поэтому и тайминг тут ни при чём.
    if (!(method === 'POST' && (path || '').split('?')[0] === site.ingestPath && body && body.length >= 48)) {
      return asSite();
    }

    // Единый путь и для успеха, и для провала.
    const res = nodeHandshake(nodePriv, body, { seen, nowSec: nowSec() });
    if (!res.ok) return asSite();   // не наш — ведём себя как форма

    return {
      kind: 'tunnel',
      session: res.session,
      reply: res.reply,             // уйдёт в теле ответа несущей
      reader: makeFrameReader(),    // дальше клиент шлёт кадры данных
    };
  }

  return { handle, site };
}
